// ฟังก์ชันดึงข้อสอบสุ่มตามระดับความยาก
function getRandomQuestions(easyCount, mediumCount, hardCount) {
  const easyPool = QUESTION_BANK.filter(q => q.difficulty === 'easy');
  const mediumPool = QUESTION_BANK.filter(q => q.difficulty === 'medium');
  const hardPool = QUESTION_BANK.filter(q => q.difficulty === 'hard');

  // Fisher-Yates shuffle algorithm สำหรับการสุ่มที่กระจายตัวสม่ำเสมอ
  const shuffle = arr => {
    const copy = [...arr];
    for (let i = copy.length - 1; i > 0; i--) {
      const j = Math.floor(Math.random() * (i + 1));
      [copy[i], copy[j]] = [copy[j], copy[i]];
    }
    return copy;
  };

  const selectedEasy = shuffle(easyPool).slice(0, Math.min(easyCount, easyPool.length));
  const selectedMedium = shuffle(mediumPool).slice(0, Math.min(mediumCount, mediumPool.length));
  const selectedHard = shuffle(hardPool).slice(0, Math.min(hardCount, hardPool.length));

  // รวมและสลับลำดับข้อสอบทั้งหมด
  return shuffle([...selectedEasy, ...selectedMedium, ...selectedHard]);
}
