// ฟังก์ชันสุ่มข้อสอบตามระดับความยาก, ระดับชั้น, หมวดวิชา และรวมข้อสอบที่ครูสร้างเอง
function getRandomQuestions(easyCount, mediumCount, hardCount, grade = null, subject = null, customQuestions = []) {
  let pool = [...QUESTION_BANK, ...(customQuestions || [])];
  
  if (grade && grade !== 'all') {
    pool = pool.filter(q => q.grade === grade);
  }
  
  if (subject && subject !== 'all') {
    pool = pool.filter(q => q.subject === subject || (q.category && q.category.includes(subject)));
  }

  const easyPool = pool.filter(q => q.difficulty === 'easy');
  const mediumPool = pool.filter(q => q.difficulty === 'medium');
  const hardPool = pool.filter(q => q.difficulty === 'hard');

  const shuffle = arr => {
    const copy = [...arr];
    for (let i = copy.length - 1; i > 0; i--) {
      const j = Math.floor(Math.random() * (i + 1));
      [copy[i], copy[j]] = [copy[j], copy[i]];
    }
    return copy;
  };

  const selectedEasy = shuffle(easyPool).slice(0, Math.min(easyCount, easyPool.length));
  const selectedMedium = shuffle(mediumPool).slice(0, Math.min(mediumCount, mediumPool.length));
  const selectedHard = shuffle(hardPool).slice(0, Math.min(hardCount, hardPool.length));

  return shuffle([...selectedEasy, ...selectedMedium, ...selectedHard]);
}